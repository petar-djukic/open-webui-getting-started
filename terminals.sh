#!/bin/sh
# Starts the stack and keeps Open WebUI's terminal list in sync with it: the main
# terminal plus one terminal per folder in terminals.txt. A folder terminal can write
# only to its folder and reads the rest of that folder's top-level directory.
set -eu

here=$(cd "$(dirname "$0")" && pwd -P)
home=$(cd "$HOME" && pwd -P)
list="$here/terminals.txt"
out="$here/terminals.yml"
env="$here/.env"
self_rel=${here#"$home"/}

usage() {
    cat >&2 <<'EOF'
Usage: ./terminals.sh <command> [folder]
  sync            Start or update everything and register the terminals in Open WebUI
  add <folder>    Add a terminal that can write only to <folder>
  remove <folder> Remove that terminal (its home volume is kept)
  list            Show the folder terminals and whether they are running
EOF
    exit 1
}

# A listed entry, or a directory under $HOME, as a path relative to $HOME.
resolve() {
    if [ -f "$list" ] && grep -qxF "$1" "$list"; then
        printf '%s\n' "$1"
        return
    fi
    [ -d "$1" ] || { echo "Not a directory: $1" >&2; exit 1; }
    abs=$(cd "$1" && pwd -P)
    case "$abs" in
        "$home"/*/*) printf '%s\n' "${abs#"$home"/}" ;;
        *) echo "Must be at least two levels under \$HOME: $abs" >&2; exit 1 ;;
    esac
}

slug() { printf '%s' "$1" | tr 'A-Z' 'a-z' | sed 's/[^a-z0-9][^a-z0-9]*/-/g; s/^-//; s/-$//'; }
var() { printf 'TERM_%s' "$(slug "$1" | tr 'a-z-' 'A-Z_')"; }
env_get() { grep "^$1=" "$env" | tail -1 | cut -d= -f2- | sed 's/^"//; s/"$//'; }

env_append() {
    [ -s "$env" ] && [ -n "$(tail -c1 "$env")" ] && echo >> "$env"
    printf '%s\n' "$1" >> "$env"
}

# Fills in what .env needs beyond the user's settings: API keys and COMPOSE_FILE.
ensure_env() {
    [ -f "$env" ] || { echo "Missing .env: run cp .env.example .env and edit it." >&2; exit 1; }
    [ -n "$(env_get OPEN_TERMINAL_API_KEY)" ] || env_append "OPEN_TERMINAL_API_KEY=$(openssl rand -hex 32)"
    grep -q '^COMPOSE_FILE=' "$env" || env_append 'COMPOSE_FILE=docker-compose.yml:terminals.yml'
    if [ -f "$list" ]; then
        while IFS= read -r entry; do
            [ -n "$entry" ] || continue
            v=$(var "$entry")
            [ -n "$(env_get "${v}_KEY")" ] || env_append "${v}_KEY=$(openssl rand -hex 32)"
        done < "$list"
    fi
}

# Hides this folder, which holds .env, inside terminals that can see it.
mask() {
    case "$self_rel" in
        "$1"/*) printf '    tmpfs:\n      - "/home/user/%s"\n' "$self_rel" ;;
    esac
}

generate() {
    {
        echo "# Generated by ./terminals.sh from terminals.txt. Do not edit."
        echo "services:"
        echo "  open-terminal:"
        ws=$(env_get WORKSPACE)
        if [ -n "$ws" ] && [ -n "$(mask "$ws")" ]; then mask "$ws"; else echo "    {}"; fi
        vols=""
        if [ -f "$list" ]; then
            while IFS= read -r entry; do
                [ -n "$entry" ] || continue
                s=$(slug "$entry")
                v=$(var "$entry")
                root=${entry%%/*}
                vols="$vols term-$s"
                cat <<EOF
  term-$s:
    image: open-terminal-gh
    pull_policy: never
    container_name: term-$s
    restart: unless-stopped
    depends_on: [open-terminal]
    command: ["run", "--cwd", "/home/user/$entry"]
    volumes:
      - "term-$s:/home/user"
      - "\${HOME}/$root:/home/user/$root:ro"
      - "\${HOME}/$entry:/home/user/$entry"
EOF
                mask "$root"
                cat <<EOF
    environment:
      - OPEN_TERMINAL_API_KEY=\${${v}_KEY:?run ./terminals.sh sync}
      - GIT_AUTHOR_NAME=\${GIT_USER_NAME}
      - GIT_AUTHOR_EMAIL=\${GIT_USER_EMAIL}
      - GIT_COMMITTER_NAME=\${GIT_USER_NAME}
      - GIT_COMMITTER_EMAIL=\${GIT_USER_EMAIL}
      - GH_TOKEN=\${${v}_GH_TOKEN:-}
      - GITLAB_TOKEN=\${${v}_GITLAB_TOKEN:-}
      - GITLAB_HOST=\${GITLAB_HOST:-gitlab.com}
EOF
            done < "$list"
        fi
        if [ -n "$vols" ]; then
            echo "volumes:"
            for s in $vols; do echo "  $s:"; done
        fi
    } > "$out"
}

# Mints a five-minute session token for the first admin inside the open-webui
# container, signed with its secret key, so no API key has to be created by hand.
token_py='
import datetime, sqlite3, uuid, jwt
env = dict(v.split("=", 1) for v in open("/proc/1/environ").read().split("\0") if "=" in v)
row = sqlite3.connect("/app/backend/data/webui.db").execute(
    "select u.id, a.session_stamp from user u join auth a on a.id = u.id"
    " where u.role = ? order by u.created_at limit 1", ("admin",)).fetchone()
if not row:
    raise SystemExit("No admin account yet: open http://localhost:3000, create one, then run ./terminals.sh sync again.")
now = datetime.datetime.now(datetime.timezone.utc)
print(jwt.encode({"id": row[0], "session_stamp": row[1], "typ": "session", "auth_method": "password",
                  "iat": now, "exp": now + datetime.timedelta(minutes=5), "jti": str(uuid.uuid4())},
                 env["WEBUI_SECRET_KEY"], algorithm="HS256"))
'

# Replaces the connections this script owns (id prefix "repo-terminal:") and leaves
# every other connection alone. Keeps the enabled/config choices made in the UI.
register_py='
import json, os, sys, urllib.error, urllib.request
base = "http://localhost:3000/api/v1/configs/terminal_servers"
headers = {"Authorization": "Bearer " + os.environ["OWUI_KEY"], "Content-Type": "application/json"}

def call(method, body=None):
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(base, data=data, headers=headers, method=method)
    with urllib.request.urlopen(req, timeout=15) as r:
        return json.load(r)

try:
    current = call("GET")["TERMINAL_SERVER_CONNECTIONS"] or []
except urllib.error.HTTPError as e:
    sys.exit("Open WebUI refused the request (%d)." % e.code)

prefix = "repo-terminal:"
old = {c["id"]: c for c in current if str(c.get("id", "")).startswith(prefix)}
kept = [c for c in current if c.get("id") not in old]
managed = []
for line in sys.stdin:
    cid, name, host, key = line.rstrip("\n").split("\t")
    prev = old.get(prefix + cid, {})
    managed.append({
        "id": prefix + cid, "name": name, "enabled": prev.get("enabled", True),
        "url": "http://%s:8000" % host, "path": "/openapi.json", "key": key,
        "auth_type": "bearer", "forward_cookies": False,
        "config": prev.get("config") or {"access_grants": [], "working_directory_context": True, "user_shell_tools": "auto"},
    })
call("POST", {"TERMINAL_SERVER_CONNECTIONS": kept + managed})
print("Open WebUI lists %d terminal(s)." % len(managed))
'

register() {
    printf 'Waiting for Open WebUI'
    i=0
    until curl -fs -o /dev/null http://localhost:3000/health; do
        i=$((i + 1))
        [ $i -lt 60 ] || { echo; echo "Open WebUI did not come up on http://localhost:3000." >&2; exit 1; }
        printf '.'
        sleep 2
    done
    echo
    owui_key=$(env_get OPEN_WEBUI_API_KEY)
    [ -n "$owui_key" ] || owui_key=$(docker exec open-webui python3 -c "$token_py")
    {
        printf 'main\t~/%s\topen-terminal\t%s\n' "$(env_get WORKSPACE)" "$(env_get OPEN_TERMINAL_API_KEY)"
        if [ -f "$list" ]; then
            while IFS= read -r entry; do
                [ -n "$entry" ] || continue
                printf '%s\t~/%s\tterm-%s\t%s\n' "$(slug "$entry")" "$entry" "$(slug "$entry")" "$(env_get "$(var "$entry")_KEY")"
            done < "$list"
        fi
    } | OWUI_KEY="$owui_key" python3 -I -c "$register_py"
}

apply() {
    ensure_env
    generate
    (cd "$here" && docker compose up -d --build --remove-orphans)
    register
}

[ $# -ge 1 ] || usage
cmd=$1
shift

case "$cmd" in
    sync)
        apply
        ;;
    add)
        [ $# -eq 1 ] || usage
        rel=$(resolve "$1")
        [ "$rel" != "$self_rel" ] || { echo "This folder holds .env; it cannot get a terminal." >&2; exit 1; }
        touch "$list"
        grep -qxF "$rel" "$list" || printf '%s\n' "$rel" >> "$list"
        apply
        echo "In a new chat, pick ~/$rel from the terminal icon."
        ;;
    remove)
        [ $# -eq 1 ] || usage
        rel=$(resolve "$1")
        grep -vxF "$rel" "$list" > "$list.tmp" || true
        mv "$list.tmp" "$list"
        sed -i.bak "/^$(var "$rel")_KEY=/d" "$env" && rm -f "$env.bak"
        apply
        ;;
    list)
        [ -s "$list" ] || { echo "No folder terminals."; exit 0; }
        while IFS= read -r entry; do
            [ -n "$entry" ] || continue
            state=$(docker inspect -f '{{.State.Status}}' "term-$(slug "$entry")" 2>/dev/null || echo "not created")
            printf '~/%-48s %s\n' "$entry" "$state"
        done < "$list"
        ;;
    *)
        usage
        ;;
esac
