#!/bin/sh
# Manages per-repository terminals. Each one can write only to its repository and
# reads the rest of the repository's top-level folder (e.g. ~/projects) read-only.
# The list lives in terminals.txt; the generated services go to terminals.yml.
set -eu

here=$(cd "$(dirname "$0")" && pwd -P)
home=$(cd "$HOME" && pwd -P)
list="$here/terminals.txt"
out="$here/terminals.yml"
env="$here/.env"
self_rel=${here#"$home"/}

usage() {
    cat >&2 <<'EOF'
Usage: ./terminals.sh <command> [dir]
  add <dir>      Add a terminal that can write only to <dir> and register it in Open WebUI
  remove <dir>   Remove that terminal and its connection (its home volume is kept)
  list           Show the terminals and their connection URLs
  key <dir>      Copy a terminal's API key to the clipboard
  sync           Regenerate terminals.yml, apply it and re-register the connections
EOF
    exit 1
}

# A listed entry, or a directory under $HOME, as a path relative to $HOME.
resolve() {
    if [ -f "$list" ] && grep -qxF "$1" "$list"; then
        printf '%s\n' "$1"
        return
    fi
    [ -d "$1" ] || { echo "Not a directory: $1" >&2; exit 1; }
    abs=$(cd "$1" && pwd -P)
    case "$abs" in
        "$home"/*/*) printf '%s\n' "${abs#"$home"/}" ;;
        *) echo "Must be at least two levels under \$HOME: $abs" >&2; exit 1 ;;
    esac
}

slug() { printf '%s' "$1" | tr 'A-Z' 'a-z' | sed 's/[^a-z0-9][^a-z0-9]*/-/g; s/^-//; s/-$//'; }
var() { printf 'TERM_%s' "$(slug "$1" | tr 'a-z-' 'A-Z_')"; }

env_append() {
    [ -s "$env" ] && [ -n "$(tail -c1 "$env")" ] && echo >> "$env"
    printf '%s\n' "$1" >> "$env"
}

ensure_env() {
    [ -f "$env" ] || { echo "Missing .env; create it first (see README)." >&2; exit 1; }
    grep -q '^COMPOSE_FILE=' "$env" || env_append 'COMPOSE_FILE=docker-compose.yml:terminals.yml'
    if [ -f "$list" ]; then
        while IFS= read -r entry; do
            [ -n "$entry" ] || continue
            v=$(var "$entry")
            grep -q "^${v}_KEY=" "$env" || env_append "${v}_KEY=$(openssl rand -hex 32)"
        done < "$list"
    fi
}

# Hides this folder, which holds .env, inside terminals that can see it.
mask() {
    case "$self_rel" in
        "$1"/*) printf '    tmpfs:\n      - "/home/user/%s"\n' "$self_rel" ;;
    esac
}

generate() {
    {
        echo "# Generated by ./terminals.sh from terminals.txt. Do not edit."
        echo "services:"
        echo "  open-terminal:"
        ws=$(grep '^WORKSPACE=' "$env" | cut -d= -f2-)
        if [ -n "$ws" ] && [ -n "$(mask "$ws")" ]; then mask "$ws"; else echo "    {}"; fi
        vols=""
        if [ -f "$list" ]; then
            while IFS= read -r entry; do
                [ -n "$entry" ] || continue
                s=$(slug "$entry")
                v=$(var "$entry")
                root=${entry%%/*}
                vols="$vols term-$s"
                cat <<EOF
  term-$s:
    image: open-terminal-gh
    pull_policy: never
    container_name: term-$s
    restart: unless-stopped
    depends_on: [open-terminal]
    command: ["run", "--cwd", "/home/user/$entry"]
    volumes:
      - "term-$s:/home/user"
      - "\${HOME}/$root:/home/user/$root:ro"
      - "\${HOME}/$entry:/home/user/$entry"
EOF
                mask "$root"
                cat <<EOF
    environment:
      - OPEN_TERMINAL_API_KEY=\${${v}_KEY:?run ./terminals.sh sync}
      - GIT_USER_NAME=\${GIT_USER_NAME:-}
      - GIT_USER_EMAIL=\${GIT_USER_EMAIL:-}
      - GIT_ALT_REMOTE=\${GIT_ALT_REMOTE:-}
      - GIT_ALT_EMAIL=\${GIT_ALT_EMAIL:-}
      - GH_TOKEN=\${${v}_GH_TOKEN:-}
      - GITLAB_TOKEN=\${${v}_GITLAB_TOKEN:-}
      - GITLAB_HOST=\${GITLAB_HOST:-gitlab.com}
EOF
            done < "$list"
        fi
        if [ -n "$vols" ]; then
            echo "volumes:"
            for s in $vols; do echo "  $s:"; done
        fi
    } > "$out"
}

# Replaces the connections this script owns (id prefix "repo-terminal:") with one per
# listed folder, named after the folder. Keeps their enabled/config edits and never
# touches other connections.
register_py='
import json, os, sys, urllib.error, urllib.request
base = os.environ["OWUI_URL"].rstrip("/") + "/api/v1/configs/terminal_servers"
headers = {"Authorization": "Bearer " + os.environ["OWUI_KEY"], "Content-Type": "application/json"}

def call(method, body=None):
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(base, data=data, headers=headers, method=method)
    with urllib.request.urlopen(req, timeout=15) as r:
        return json.load(r)

try:
    current = call("GET")["TERMINAL_SERVER_CONNECTIONS"] or []
except urllib.error.HTTPError as e:
    sys.exit("Open WebUI refused the request (%d). OPEN_WEBUI_API_KEY must be an admin API key." % e.code)
except urllib.error.URLError as e:
    sys.exit("Cannot reach Open WebUI at %s: %s" % (os.environ["OWUI_URL"], e.reason))

prefix = "repo-terminal:"
old = {c["id"]: c for c in current if str(c.get("id", "")).startswith(prefix)}
kept = [c for c in current if c.get("id") not in old]
managed = []
for line in sys.stdin:
    rel, slug, key = line.rstrip("\n").split("\t")
    cid = prefix + slug
    prev = old.get(cid, {})
    managed.append({
        "id": cid,
        "name": "~/" + rel,
        "enabled": prev.get("enabled", True),
        "url": "http://term-%s:8000" % slug,
        "path": "/openapi.json",
        "key": key,
        "auth_type": "bearer",
        "forward_cookies": False,
        "config": prev.get("config") or {"access_grants": [], "working_directory_context": True, "user_shell_tools": "auto"},
    })
call("POST", {"TERMINAL_SERVER_CONNECTIONS": kept + managed})
print("Open WebUI: %d folder terminal(s) registered." % len(managed))
'

# Mints a five-minute session token for the first admin inside the open-webui container,
# signed with its secret key, so no API key has to be created by hand.
token_py='
import datetime, sqlite3, uuid, jwt
# The server process holds the signing key it actually uses.
env = dict(v.split("=", 1) for v in open("/proc/1/environ").read().split("\0") if "=" in v)
secret = env["WEBUI_SECRET_KEY"]
row = sqlite3.connect("/app/backend/data/webui.db").execute(
    "select u.id, a.session_stamp from user u join auth a on a.id = u.id"
    " where u.role = ? order by u.created_at limit 1", ("admin",)).fetchone()
if not row:
    raise SystemExit("No admin account in Open WebUI yet; sign up first.")
now = datetime.datetime.now(datetime.timezone.utc)
print(jwt.encode({"id": row[0], "session_stamp": row[1], "typ": "session", "auth_method": "password",
                  "iat": now, "exp": now + datetime.timedelta(minutes=5), "jti": str(uuid.uuid4())},
                 secret, algorithm="HS256"))
'

register() {
    api_key=$(grep '^OPEN_WEBUI_API_KEY=' "$env" | cut -d= -f2-)
    if [ -z "$api_key" ]; then
        api_key=$(docker exec open-webui python3 -c "$token_py") || {
            echo "Could not get an admin token from the open-webui container; connections were not updated." >&2
            return 0
        }
    fi
    owui_url=$(grep '^OPEN_WEBUI_URL=' "$env" | cut -d= -f2-)
    {
        if [ -f "$list" ]; then
            while IFS= read -r entry; do
                [ -n "$entry" ] || continue
                v=$(var "$entry")
                printf '%s\t%s\t%s\n' "$entry" "$(slug "$entry")" "$(grep "^${v}_KEY=" "$env" | cut -d= -f2-)"
            done < "$list"
        fi
    } | OWUI_URL="${owui_url:-http://localhost:3000}" OWUI_KEY="$api_key" python3 -I -c "$register_py"
}

apply() {
    ensure_env
    generate
    (cd "$here" && docker compose up -d --remove-orphans)
    register
}

copy_key() {
    v=$(var "$1")
    grep "^${v}_KEY=" "$env" | cut -d= -f2- | tr -d '\n' | pbcopy
    echo "Copied the API key for $1 to the clipboard."
}

[ $# -ge 1 ] || usage
cmd=$1
shift

case "$cmd" in
    add)
        [ $# -eq 1 ] || usage
        rel=$(resolve "$1")
        [ "$rel" != "$self_rel" ] || { echo "Refusing to scope a terminal to this folder; it holds .env." >&2; exit 1; }
        touch "$list"
        grep -qxF "$rel" "$list" || printf '%s\n' "$rel" >> "$list"
        apply
        echo "In a new chat, pick ~/$rel from the terminal icon."
        ;;
    remove)
        [ $# -eq 1 ] || usage
        rel=$(resolve "$1")
        grep -vxF "$rel" "$list" > "$list.tmp" || true
        mv "$list.tmp" "$list"
        v=$(var "$rel")
        sed -i '' "/^${v}_KEY=/d" "$env"
        apply
        echo "Removed ~/$rel."
        ;;
    list)
        [ -s "$list" ] || { echo "No per-repository terminals."; exit 0; }
        while IFS= read -r rel; do
            [ -n "$rel" ] || continue
            s=$(slug "$rel")
            state=$(docker inspect -f '{{.State.Status}}' "term-$s" 2>/dev/null || echo "not created")
            printf '%-50s http://term-%s:8000  %s\n' "$rel" "$s" "$state"
        done < "$list"
        ;;
    key)
        [ $# -eq 1 ] || usage
        copy_key "$(resolve "$1")"
        ;;
    sync)
        apply
        ;;
    *)
        usage
        ;;
esac
